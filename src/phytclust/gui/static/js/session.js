function getPath(object, path) {
  const parts = path.split(".");
  let current = object;
  for (const name of parts) {
    if (!current || typeof current !== "object" || !Object.hasOwn(current, name)) return undefined;
    current = current[name];
  }
  return current;
}

function setPath(object, path, value) {
  const parts = path.split(".");
  let current = object;
  for (let i = 0; i < parts.length - 1; i++) {
    if (current[parts[i]] == null || typeof current[parts[i]] !== "object") {
      current[parts[i]] = {};
    }
    current = current[parts[i]];
  }
  current[parts[parts.length - 1]] = value;
}

function readField(field) {
  const input = document.getElementById(field.id);
  if (!input) return null;
  switch (field.type) {
    case "text": {
      const text = (input.value || "").trim();
      return text || null;
    }
    case "int":
    case "float": {
      const text = input.value.trim();
      if (!text) return null;
      const number = Number(text);
      return Number.isFinite(number) &&
        (field.type !== "int" || Number.isSafeInteger(number)) ? number : null;
    }
    case "checkbox":
      return !!input.checked;
    case "select":
      return input.value;
    default:
      return null;
  }
}

function writeField(field, value) {
  const input = document.getElementById(field.id);
  if (!input) return false;
  switch (field.type) {
    case "text":
    case "select":
      input.value = value == null ? "" : String(value);
      break;
    case "int":
    case "float":
      input.value = value == null ? "" : String(value);
      break;
    case "checkbox":
      input.checked = !!value;
      break;
  }
  // Notify any listeners (mode selector, validation, etc.)
  input.dispatchEvent(new Event("input", { bubbles: true }));
  input.dispatchEvent(new Event("change", { bubbles: true }));
  return true;
}

function readMode() {
  const active = document.querySelector("#mode-selector .mode-btn.active");
  return active ? active.dataset.mode : "global";
}

function writeMode(mode) {
  const button = [...document.querySelectorAll("#mode-selector .mode-btn")]
    .find((button) => button.dataset.mode === mode);
  if (!button) return false;
  button.click();
  return true;
}

/** Collect the current settings. Results are regenerated by Run. */
export function collectSession({ includeNewick = true } = {}) {
  const session = {
    version: SESSION_VERSION,
    saved_at: new Date().toISOString(),
    params: { mode: readMode() },
    appearance: structuredClone(state.render),
    view: {},
  };

  for (const field of PARAM_FIELDS) {
    setPath(session, field.path, readField(field));
  }

  if (includeNewick) {
    const newickEl = document.getElementById("newick-input");
    const raw = newickEl && newickEl.value ? newickEl.value.trim() : "";
    if (raw) session.newick = raw;
  }

  const selector = document.getElementById("cluster-select");
  const result = state.latestApiData;
  if (selector && result) {
    const counts = state.CLUSTER_VIEW_MODE === "all" ? result.all_ks : result.k_values || result.ks;
    const selectedCount = counts?.[Number(selector.value)];
    if (Number.isSafeInteger(selectedCount) && selectedCount > 0) {
      session.view.selected_k = selectedCount;
      session.view.cluster_mode = state.CLUSTER_VIEW_MODE;
    }
  } else if (state.pendingSessionView) {
    session.view = { ...state.pendingSessionView };
  }

  return session;
}

function isObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

function fieldValueIsValid(field, value) {
  if (field.type === "checkbox") return typeof value === "boolean";
  if (value === null) return field.type !== "select";
  if (field.type === "int") return Number.isSafeInteger(value);
  if (field.type === "float") return typeof value === "number" && Number.isFinite(value);
  if (typeof value !== "string") return false;
  if (field.type === "select") {
    const input = document.getElementById(field.id);
    return !input || [...input.options].some((option) => option.value === value);
  }
  return true;
}

/** Restore saved settings without running the clustering. Report skipped values. */
export function applySession(session) {
  const errors = [];
  if (!isObject(session) || !Number.isSafeInteger(session.version) ||
      session.version < 1 || !isObject(session.params)) {
    return { applied: 0, errors: ["Expected a session object with a version and parameters."], hadNewick: false };
  }
  if (session.version > SESSION_VERSION) {
    errors.push(`Session version ${session.version} is newer than this application. Some settings may be skipped.`);
  }
  let applied = 0;
  if (session.params.mode !== undefined) {
    if (writeMode(session.params.mode)) applied++;
    else errors.push("Unknown clustering mode in session.");
  }
  for (const field of PARAM_FIELDS) {
    const value = getPath(session, field.path);
    if (value === undefined) continue;
    if (!fieldValueIsValid(field, value)) {
      errors.push(`Invalid session setting: ${field.path}`);
    } else if (writeField(field, value)) {
      applied++;
    }
  }
  if (session.appearance !== undefined) {
    try {
      validateAppearance(session.appearance, state.render);
      state.render = renderOptionsWithOverrides(session.appearance);
      applied++;
    } catch (error) {
      errors.push(`Appearance settings were skipped: ${error.message}`);
    }
  }
  state.pendingSessionView = null;
  if (session.version >= 2 && session.view?.selected_k !== undefined) {
    if (Number.isSafeInteger(session.view.selected_k) && session.view.selected_k > 0 &&
        ["peaks", "all", undefined].includes(session.view.cluster_mode)) {
      state.pendingSessionView = {
        selected_k: session.view.selected_k,
        cluster_mode: session.view.cluster_mode || "peaks",
      };
    } else errors.push("Invalid saved cluster selection.");
  }
  let hadNewick = false;
  if (typeof session.newick === "string" && session.newick.trim()) {
    const input = document.getElementById("newick-input");
    if (input) {
      input.value = session.newick.trim();
      input.dispatchEvent(new Event("input", { bubbles: true }));
      input.dispatchEvent(new Event("change", { bubbles: true }));
      hadNewick = true;
    }
  } else if (session.newick !== undefined && typeof session.newick !== "string") {
    errors.push("The saved tree must be Newick text.");
  }
  return { applied, errors, hadNewick };
}

function validateAppearance(changes, settings, parentPath = "") {
  if (!isObject(changes)) throw new Error("Expected an object.");
  for (const [name, value] of Object.entries(changes)) {
    const path = parentPath ? `${parentPath}.${name}` : name;
    if (!Object.hasOwn(settings, name)) throw new Error(`Unknown display setting: ${path}`);
    const current = settings[name];
    if (isObject(current)) validateAppearance(value, current, path);
    else if (current === null ? value !== null && typeof value !== "string" :
      typeof value !== typeof current ||
      (typeof value === "number" && (!Number.isFinite(value) || value < 0)) ||
      (typeof value === "string" && !(
        path === "layout" ? ["rectangular", "cladogram", "circular"] : ["bars", "boxes"]
      ).includes(value))) {
      throw new Error(`Invalid display setting: ${path}`);
    }
  }
}

export function sessionSizeWarning(session) {
  if (!session.newick) return null;
  const kb = new TextEncoder().encode(session.newick).length / 1024;
  return kb > NEWICK_EMBED_LIMIT_KB
    ? `Embedded Newick is ${kb.toFixed(0)} KB. Consider saving without the tree.`
    : null;
}

export function isSessionJson(text) {
  try {
    const parsed = JSON.parse(text);
    return isObject(parsed) && Number.isSafeInteger(parsed.version) &&
      parsed.version >= 1 && isObject(parsed.params);
  } catch {
    return false;
  }
}
